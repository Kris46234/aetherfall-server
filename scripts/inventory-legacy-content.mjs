import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const sourcePath = new URL('../apps/client/src/game-runtime.js', import.meta.url);
const outputPath = new URL('../reports/legacy-content-inventory.json', import.meta.url);
const generatedPath = new URL('../packages/content/generated/catalogue.generated.js', import.meta.url);
const source = await readFile(sourcePath, 'utf8');

function statement(start, end) {
  const from = source.indexOf(start);
  const to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`Could not extract ${start}`);
  return source.slice(from, to);
}

const catalogueSource = [
  statement('const COLORS=', 'const BALANCE='),
  statement('const AB=', 'const SUPPORTED_TALENT_ABILITY_TYPES='),
  'globalThis.__catalogue={COLORS,AB,CLASS_INFO,TALENT_UNLOCKED_ABILITIES};'
].join('\n');

const sandbox = { Object, Set };
vm.createContext(sandbox);
vm.runInContext(catalogueSource, sandbox, { timeout: 1000 });
const { AB, CLASS_INFO, TALENT_UNLOCKED_ABILITIES } = sandbox.__catalogue;

const slug = (value) => String(value)
  .normalize('NFKD')
  .replace(/[’']/g, '')
  .replace(/[^a-zA-Z0-9]+/g, '_')
  .replace(/^_+|_+$/g, '')
  .toLowerCase();

function copyAbility(ability, id, sourceType, classId, slot = null) {
  const raw = JSON.parse(JSON.stringify(ability));
  const runtimeCost = sourceType === 'talent' && raw.cost
    ? Math.max(1, Math.ceil(raw.cost * .30))
    : raw.cost;
  const normalized = {
    ...raw,
    id,
    classId,
    source: sourceType,
    slot,
    castTime: raw.cast,
    cooldown: raw.cd,
    baseValue: raw.value,
    definedCost: raw.cost,
    cost: runtimeCost,
    offGlobal: /off[- ]global|off the global cooldown/i.test(raw.tip || '')
  };
  delete normalized.cast;
  delete normalized.cd;
  delete normalized.value;
  return normalized;
}

const classes = Object.keys(CLASS_INFO).sort().map((classId) => {
  const info = CLASS_INFO[classId];
  const base = (AB[classId] || []).map((ability, index) =>
    copyAbility(ability, `${classId}.${slug(ability.name)}`, 'base', classId, index + 1));
  const talents = Object.entries(TALENT_UNLOCKED_ABILITIES[classId] || {})
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([talentId, ability]) => copyAbility(ability, talentId, 'talent', classId));
  return {
    id: classId,
    name: info.name,
    role: info.role,
    resource: info.resource,
    baseAbilities: base,
    talentAbilities: talents
  };
});

const payload = {
  formatVersion: 1,
  generatedFrom: 'apps/client/src/game-runtime.js',
  note: 'Server-readable migration catalogue. The legacy browser runtime remains live authority until combat parity is complete.',
  totals: {
    classes: classes.length,
    baseAbilities: classes.reduce((n, entry) => n + entry.baseAbilities.length, 0),
    talentAbilities: classes.reduce((n, entry) => n + entry.talentAbilities.length, 0)
  },
  classes
};
const canonical = JSON.stringify(payload);
payload.sourceDigest = createHash('sha256').update(canonical).digest('hex');

await mkdir(new URL('../reports/', import.meta.url), { recursive: true });
await mkdir(new URL('../packages/content/generated/', import.meta.url), { recursive: true });
await writeFile(outputPath, `${JSON.stringify(payload, null, 2)}\n`);
await writeFile(generatedPath, [
  '// Generated by scripts/inventory-legacy-content.mjs. Do not edit by hand.',
  `export const generatedCatalogue = ${JSON.stringify(payload, null, 2)};`,
  ''
].join('\n'));
console.log(`Inventoried ${payload.totals.classes} classes, ${payload.totals.baseAbilities} base abilities and ${payload.totals.talentAbilities} talent abilities.`);
